"""Builds src/components/worldDots.js, the dotted world map behind the check-in card.

Input: Natural Earth 1:110m land (public domain), ne_110m_land.geojson from
https://github.com/nvkelso/natural-earth-vector/tree/master/geojson

    python3 scripts/world-dots.py path/to/ne_110m_land.geojson
"""

import json
import sys
from pathlib import Path

STEP = 2.5  # degrees between dots
NORTH, SOUTH = 78.0, -58.0  # leave out the poles: Antarctica and the Arctic only add noise
OUT = Path(__file__).resolve().parent.parent / "src" / "components" / "worldDots.js"


def polygons_of(geometry):
	return geometry["coordinates"] if geometry["type"] == "MultiPolygon" else [geometry["coordinates"]]


def inside(ring, lon, lat):
	hit = False
	for (x1, y1), (x2, y2) in zip(ring, ring[1:] + ring[:1], strict=True):
		if (y1 > lat) != (y2 > lat) and lon < (x2 - x1) * (lat - y1) / (y2 - y1) + x1:
			hit = not hit
	return hit


def on_land(polygons, lon, lat):
	return any(inside(p[0], lon, lat) and not any(inside(h, lon, lat) for h in p[1:]) for p in polygons)


def main(source):
	features = json.loads(Path(source).read_text())["features"]
	polygons = [p for f in features for p in polygons_of(f["geometry"])]
	dots = []
	lat = NORTH - STEP / 2
	while lat > SOUTH:
		lon = -180 + STEP / 2
		while lon < 180:
			if on_land(polygons, lon, lat):
				dots.append(f"M{lon + 180:g} {NORTH - lat:g}h0")
			lon += STEP
		lat -= STEP
	OUT.write_text(
		"// Generated by scripts/world-dots.py from Natural Earth 1:110m land (public domain).\n"
		"// x = longitude + 180, y = degrees south of the top edge.\n"
		"export const WORLD = {\n"
		f"\tnorth: {NORTH:g},\n\tsouth: {SOUTH:g},\n\tstep: {STEP:g},\n"
		f'\tpath: "{"".join(dots)}",\n'
		"};\n"
	)
	print(f"{len(dots)} dots -> {OUT}")


if __name__ == "__main__":
	main(sys.argv[1])
